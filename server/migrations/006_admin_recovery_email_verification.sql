-- Applies atomically to future account changes; does not update any existing row now.
-- Changing an email and then changing it back cannot resurrect its old verification.
CREATE FUNCTION public.invalidate_admin_recovery_email_verification()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
  IF OLD.recovery_email IS DISTINCT FROM NEW.recovery_email
     OR OLD.role IS DISTINCT FROM NEW.role
     OR OLD.status IS DISTINCT FROM NEW.status THEN
    NEW.recovery_email_verified_at := NULL;
    UPDATE public.admin_recovery_email_verification_tokens
      SET used_at = CURRENT_TIMESTAMP
      WHERE user_id = NEW.id AND used_at IS NULL;
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER invalidate_admin_recovery_email_verification_on_change
BEFORE UPDATE OF recovery_email, role, status ON public.users
FOR EACH ROW EXECUTE FUNCTION public.invalidate_admin_recovery_email_verification();

