-- Ensure no trip can be paired with more than one duty, including across
-- first_trip_id and return_trip_id. The two UNIQUE constraints above only
-- protect each column separately, so a trigger enforces the cross-column rule.
CREATE OR REPLACE FUNCTION prevent_duplicate_duty_trip()
RETURNS TRIGGER AS $$
BEGIN
  IF EXISTS (
    SELECT 1
    FROM bus_duties d
    WHERE d.id IS DISTINCT FROM NEW.id
      AND (
        d.first_trip_id IN (NEW.first_trip_id, NEW.return_trip_id)
        OR d.return_trip_id IN (NEW.first_trip_id, NEW.return_trip_id)
      )
  ) THEN
    RAISE EXCEPTION 'A trip is already assigned to a bus duty';
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS prevent_duplicate_duty_trip_insert ON bus_duties;
CREATE TRIGGER prevent_duplicate_duty_trip_insert
  BEFORE INSERT ON bus_duties
  FOR EACH ROW EXECUTE FUNCTION prevent_duplicate_duty_trip();

DROP TRIGGER IF EXISTS prevent_duplicate_duty_trip_update ON bus_duties;
CREATE TRIGGER prevent_duplicate_duty_trip_update
  BEFORE UPDATE OF first_trip_id, return_trip_id ON bus_duties
  FOR EACH ROW EXECUTE FUNCTION prevent_duplicate_duty_trip();

