BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '30s';
SELECT pg_advisory_xact_lock(8216042, 1);

-- Abort rather than choose an administrator or modify conflicting records.
LOCK TABLE users IN SHARE ROW EXCLUSIVE MODE;
DO $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM users
    WHERE role = 'admin' AND NULLIF(BTRIM(recovery_email), '') IS NOT NULL
    GROUP BY LOWER(BTRIM(recovery_email)) HAVING COUNT(*) > 1
  ) THEN
    RAISE EXCEPTION 'Administrator recovery email conflicts require owner resolution.';
  END IF;
END;
$$;

CREATE TABLE admin_username_recovery_tokens (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  email TEXT NOT NULL,
  token_hash TEXT NOT NULL UNIQUE,
  expires_at TIMESTAMPTZ NOT NULL,
  used_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_admin_username_recovery_user ON admin_username_recovery_tokens(user_id);
CREATE INDEX idx_admin_username_recovery_expiry ON admin_username_recovery_tokens(expires_at);

CREATE TABLE admin_username_recovery_limits (
  scope TEXT NOT NULL CHECK (scope IN ('request-ip', 'request-email', 'confirm-ip')),
  key_hash TEXT NOT NULL,
  window_started_at TIMESTAMPTZ NOT NULL,
  attempts INTEGER NOT NULL CHECK (attempts > 0),
  PRIMARY KEY (scope, key_hash)
);
CREATE INDEX idx_admin_username_recovery_limits_expiry ON admin_username_recovery_limits(window_started_at);

-- Supabase public-schema tables must not expose authentication metadata to clients.
ALTER TABLE admin_username_recovery_tokens ENABLE ROW LEVEL SECURITY;
ALTER TABLE admin_username_recovery_limits ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE admin_username_recovery_tokens, admin_username_recovery_limits FROM PUBLIC;
REVOKE ALL ON SEQUENCE admin_username_recovery_tokens_id_seq FROM PUBLIC;
DO $$
DECLARE client_role TEXT;
BEGIN
  FOR client_role IN SELECT rolname FROM pg_roles WHERE rolname IN ('anon', 'authenticated') LOOP
    EXECUTE format('REVOKE ALL ON TABLE admin_username_recovery_tokens, admin_username_recovery_limits FROM %I', client_role);
    EXECUTE format('REVOKE ALL ON SEQUENCE admin_username_recovery_tokens_id_seq FROM %I', client_role);
  END LOOP;
END;
$$;

-- Invalidate only the NEW username-recovery tokens when account details change.
-- The trigger never edits a user, a password-reset token or an existing session.
CREATE FUNCTION invalidate_admin_username_recovery() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
  IF OLD.recovery_email IS DISTINCT FROM NEW.recovery_email
     OR OLD.username IS DISTINCT FROM NEW.username
     OR OLD.role IS DISTINCT FROM NEW.role
     OR OLD.status IS DISTINCT FROM NEW.status THEN
    UPDATE admin_username_recovery_tokens SET used_at = CURRENT_TIMESTAMP
    WHERE user_id = NEW.id AND used_at IS NULL;
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER invalidate_admin_username_recovery_on_account_change
AFTER UPDATE OF recovery_email, username, role, status ON users
FOR EACH ROW EXECUTE FUNCTION invalidate_admin_username_recovery();

