test('unique bus IDs make left join cardinality neutral for matching, null and missing bus IDs', () => {
  const migration = readFileSync(new URL('./migrations/001_initial_postgres.sql', import.meta.url), 'utf8')
  assert.match(migration, /CREATE TABLE IF NOT EXISTS buses \(\s*id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY/)
  const buses = [{ id: 1 }, { id: 2 }]
  const trips = [{ id: 1, bus_id: 1 }, { id: 2, bus_id: null }, { id: 3, bus_id: 999 }]
  const bookings = Array.from({ length: 205 }, (_, id) => ({ id, trip_id: id % 3 + 1, travel_date: `2026-11-${id % 2 ? '10' : '11'}`, created_at: id }))
  const joined = bookings.flatMap(bk => trips.filter(t => t.id === bk.trip_id).map(t => ({ bk, t })))
  const withBuses = joined.flatMap(row => {
    const matches = buses.filter(b => b.id === row.t.bus_id)
    return (matches.length ? matches : [null]).map(() => row)
  })
  const orderedIds = rows => rows.slice().sort((a, b) => b.bk.travel_date.localeCompare(a.bk.travel_date) || b.bk.created_at - a.bk.created_at).slice(0, 200).map(row => row.bk.id)
  assert.equal(withBuses.length, joined.length)
  assert.deepEqual(orderedIds(withBuses), orderedIds(joined))
  // Equal sort keys remain ties: neither query promises their relative order.
})
