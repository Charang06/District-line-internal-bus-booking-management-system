import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import test from 'node:test'
import vm from 'node:vm'

// Read source only: never import the server, its environment loader, or pg.
const source = readFileSync(new URL('./server.js', import.meta.url), 'utf8')
const start = "app.get('/api/admin/dashboard', authMiddleware, requireDashboardScope, async (req, res) => {"
const end = "  if (scope === 'dashboard' || scope === 'accounts') {"
assert.equal(source.split(start).length, 2)
assert.equal(source.split(end).length, 2)
const branch = source.slice(source.indexOf(start) + start.length, source.indexOf(end))
const sampleSql = `SELECT bk.status, bk.confirmation_status, t.travel_date, t.route_code, bk.boarding_point
  FROM bookings bk JOIN trips t ON t.id = bk.trip_id
  ORDER BY t.travel_date DESC, bk.created_at DESC LIMIT 200`
const normalize = sql => sql.replace(/\s+/g, ' ').trim()

async function invoke(passengerRecords, regularCustomers, { role = 'admin', failure = false } = {}) {
  const queries = []
  const context = { dashboardMs: 0 }
  let body
  const handler = vm.runInNewContext(`(async (req, res) => {${branch}})`, {
    monotonicMs: () => 10,
    transactionContext: { getStore: () => context },
    all: async sql => {
      queries.push(sql)
      if (queries.length === 1) {
        assert.equal(normalize(sql), normalize(sampleSql))
        if (failure) throw new Error('synthetic query failure')
        return passengerRecords
      }
      assert.equal(queries.length, 2)
      assert.match(sql, /WITH normalized_bookings AS/)
      assert.match(sql, /WHERE bk.status = 'confirmed'/)
      assert.match(sql, /bk.confirmation_status = 'confirmed'/)
      assert.match(sql, /HAVING COUNT\(\*\) >= 2/)
      return regularCustomers
    },
  })
  await handler({ query: { scope: 'customers' }, user: { role } }, { json(value) { body = value } })
  return { body, queries }
}

test('customer branch preserves response keys, row values/order and both reads for admin and staff', async () => {
  const passengerRecords = [
    { status: 'cancelled', confirmation_status: 'pending', travel_date: '2026-11-11', route_code: 'A', boarding_point: null },
    { status: 'confirmed', confirmation_status: 'confirmed', travel_date: '2026-11-10', route_code: 'B', boarding_point: 'Town' },
  ]
  const regularCustomers = [{ passenger_name: 'Synthetic customer', contact: '+94700000000', trip_dates: ['2026-11-11', '2026-11-10'], trip_count: '2', month_count: '1', last_trip_date: '2026-11-11' }]
  for (const role of ['admin', 'staff']) {
    const { body, queries } = await invoke(passengerRecords, regularCustomers, { role })
    assert.deepEqual(Object.keys(body), ['scope', 'passengerRecords', 'regularCustomers'])
    assert.equal(body.scope, 'customers')
    assert.strictEqual(body.passengerRecords, passengerRecords)
    assert.strictEqual(body.regularCustomers, regularCustomers)
    assert.equal(queries.length, 2)
  }
})

test('empty customer results retain both arrays', async () => {
  const { body } = await invoke([], [])
  assert.equal(JSON.stringify(body), '{"scope":"customers","passengerRecords":[],"regularCustomers":[]}')
})

test('query failure propagates instead of returning a partial dashboard', async () => {
  await assert.rejects(invoke([], [], { failure: true }), /synthetic query failure/)
})

